"""A deployable build must include its worker inputs and exclude local data."""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("build_web", ROOT / "scripts/build_web.py")
builder = importlib.util.module_from_spec(spec)
spec.loader.exec_module(builder)


class WebBuildTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name) / "source"
        self.output = Path(self.temporary.name) / "site"
        for name, contents in {
            "web/landing/index.html": '<a href="/app/">Open LootLizard</a>',
            "web/landing/assets/logo.svg": "<svg/>",
            "web/app/index.html": '<script src="app.js" type="module"></script>',
            "web/app/app.js": "// browser application",
            "web/app/python_bridge.py": "# browser bridge",
            "data/erangel.json": "{}", "data/taego.json": "{}",
            "LICENSE": "MIT", "THIRD_PARTY_NOTICES.md": "Credits",
            "lootlizard/windows.py": "# legacy native code",
            ".env": "not for publication", "screenshots/private.png": "private",
            "web/app/__pycache__/python_bridge.cpython-312.pyc": "generated bytecode",
        }.items():
            self.write(name, contents)
        for filename in builder.PYTHON_MODULES:
            self.write("lootlizard/" + filename, '__version__ = "0.9.0"' if filename == "__init__.py" else "# pure CV")

    def write(self, name, content):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        return path

    def test_public_routes_include_all_worker_inputs_and_omit_checkout_secrets(self):
        assets = builder.build(self.output, root=self.root, revision="a" * 40)
        self.assertIn("index.html", assets)
        self.assertIn("app/index.html", assets)
        self.assertIn("app/python_bridge.py", assets)
        self.assertIn("404.html", assets)
        self.assertEqual({name for name in assets if name.startswith("cv/")}, {f"cv/{name}" for name in builder.PYTHON_MODULES})
        self.assertNotIn("cv/windows.py", assets)
        self.assertNotIn(".env", assets)
        self.assertNotIn("screenshots/private.png", assets)
        self.assertIn("/app /app/ 308", assets["_redirects"].decode())
        info = json.loads(assets[builder.BUILD_INFO])
        self.assertEqual(info["version"], "0.9.0")
        self.assertEqual(info["revision"], "a" * 40)
        self.assertEqual(set(info["assets"]), set(assets) - {builder.BUILD_INFO})

    def test_rebuild_removes_only_obsolete_manifest_assets(self):
        old = self.write("web/app/old.js", "// obsolete")
        builder.build(self.output, root=self.root)
        old.unlink()
        self.write("web/app/new.js", "// new")
        builder.build(self.output, root=self.root)
        self.assertFalse((self.output / "app/old.js").exists())
        self.assertTrue((self.output / "app/new.js").exists())

    def test_non_build_output_and_untracked_files_are_preserved(self):
        self.output.mkdir()
        important = self.output / "notes.txt"
        important.write_text("keep me")
        with self.assertRaisesRegex(ValueError, "Refusing to replace"):
            builder.build(self.output, root=self.root)
        self.assertEqual(important.read_text(), "keep me")
        important.unlink()
        builder.build(self.output, root=self.root)
        important.write_text("keep me")
        with self.assertRaisesRegex(ValueError, "not listed"):
            builder.build(self.output, root=self.root)
        self.assertEqual(important.read_text(), "keep me")

    def test_unexpected_source_file_and_invalid_revision_abort_before_output(self):
        self.write("web/app/private.env", "not public")
        with self.assertRaisesRegex(ValueError, "Unexpected file"):
            builder.build(self.output, root=self.root)
        self.assertFalse(self.output.exists())
        with self.assertRaisesRegex(ValueError, "revision"):
            builder.build(self.output, root=self.root, revision="not-a-commit")

    def test_manifest_paths_cannot_escape_output_or_create_windows_streams(self):
        for name in ("../outside", "/outside", "app/../../outside", "C:/outside", "app.js:secret", "app\\secret"):
            with self.subTest(name=name), self.assertRaises(ValueError):
                builder._relative_name(name)

    def test_web_release_tags_match_the_version_and_have_numeric_order(self):
        for invalid in ("v0.9.0", "v0.9.0-web.0", "v0.9.0-web.01", "v0.9.0-web.x", "v00.9.0-web.1"):
            with self.subTest(tag=invalid), self.assertRaises(ValueError):
                builder.release_key(invalid)
        self.assertGreater(builder.release_key("v0.9.0-web.10"), builder.release_key("v0.9.0-web.2"))
        self.assertGreater(builder.release_key("v0.10.0-web.1"), builder.release_key("v0.9.0-web.2"))
        assets = builder.collect_assets(self.root, tag="v0.9.0-web.1")
        self.assertEqual(json.loads(assets[builder.BUILD_INFO])["tag"], "v0.9.0-web.1")
        with self.assertRaisesRegex(ValueError, "does not match"):
            builder.collect_assets(self.root, tag="v0.8.0-web.1")

    def test_symlink_input_is_rejected_if_host_supports_it(self):
        link = self.root / "web/app/private.txt"
        try:
            link.symlink_to(self.root / ".env")
        except OSError:
            self.skipTest("This account cannot create symlinks")
        with self.assertRaisesRegex(ValueError, "symlinks"):
            builder.build(self.output, root=self.root)


if __name__ == "__main__":
    unittest.main()
