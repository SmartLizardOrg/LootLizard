/** Return the original English message when no Hungarian translation exists. */
export function translate(key, language = "en") {
  return language === "hu" && Object.hasOwn(HUNGARIAN, key)
    ? HUNGARIAN[key]
    : key;
}

/** Translate static markup; the controller renders dynamic state afterwards. */
export function applyLanguage(language = "en") {
  const selected = language === "hu" ? "hu" : "en";
  document.documentElement.lang = selected;
  for (const node of document.querySelectorAll("[data-i18n]")) {
    node.textContent = translate(node.getAttribute("data-i18n"), selected);
  }
  return selected;
}
